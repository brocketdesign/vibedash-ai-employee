// Helper to create timeline events
function createTimelineEvents(projectId: string, currentPhase: string, createdAt: string): TimelineEvent[] {
  const events: TimelineEvent[] = [
    {
      id: `evt-${projectId}-1`,
      projectId,
      type: "creation",
      title: "Project Created",
      description: "Project was initialized in VibeDash",
      date: createdAt,
    },
  ];

  // Add stage change events based on current phase
  const stageOrder = ["idea", "prototype", "free-tier", "premium", "deploy", "live"];
  const currentIndex = stageOrder.indexOf(currentPhase);
  
  for (let i = 0; i <= currentIndex && i < stageOrder.length; i++) {
    const phase = stageOrder[i];
    if (phase !== "idea") {
      events.push({
        id: `evt-${projectId}-${i + 2}`,
        projectId,
        type: "stage-change",
        title: `Moved to ${phase}`,
        description: `Project advanced to ${phase} stage`,
        date: new Date(Date.parse(createdAt) + (i + 1) * 7 * 24 * 60 * 60 * 1000).toISOString(),
        metadata: { fromStage: stageOrder[i - 1], toStage: phase },
      });
    }
  }

  return events.sort((a, b) => new Date(b.date).getTime() - new Date(a.date).getTime());
}

